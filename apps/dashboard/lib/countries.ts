export function flagOf(iso: string): string {
  return String.fromCodePoint(...[...iso.toUpperCase()].map((c) => 0x1f1e6 + c.charCodeAt(0) - 65))
}

export const PRIORITY_COUNTRIES = PRIORITY.map((iso) => COUNTRIES.find((c) => c.iso === iso)!)

export function countryByIso(iso: string): Country | undefined {
  return COUNTRIES.find((c) => c.iso === iso)
}

/** Pays d'un wa_id, pour l'affichage : indicatif le plus long qui
 *  correspond. Pour « 1 » ou « 7 », plusieurs pays partagent l'indicatif :
 *  on prend le premier de la liste prioritaire, sinon le premier trouvé —
 *  le drapeau est alors indicatif, le numéro, lui, reste exact. */
export function countryOfWaId(waId: string): Country | undefined {
  const matches = COUNTRIES.filter((c) => waId.startsWith(c.dial))
  if (matches.length === 0) return undefined
  const longest = Math.max(...matches.map((c) => c.dial.length))
  const best = matches.filter((c) => c.dial.length === longest)
  return PRIORITY_COUNTRIES.find((c) => best.includes(c)) ?? best[0]
}
